/* ---------------------------------------------------------------------
   0. LIMPIEZA
   -------------------------------------------------------------------- */
   
BEGIN
  FOR t IN (
    SELECT table_name
      FROM user_tables
     WHERE table_name IN (
           'RESENA', 'PAGO', 'PAGO_TOTAL', 'RESERVA_SERVICIO', 'RESERVA_NOCHE',
           'RESERVA_HABITACION', 'RESERVA', 'SERVICIO', 'USUARIO_SISTEMA',
           'TELEFONO_CLIENTE', 'CLIENTE', 'TARIFA', 'TEMPORADA', 'HABITACION',
           'CORREO_ALOJAMIENTO', 'TELEFONO_ALOJAMIENTO', 'ALOJAMIENTO',
           'ESTADO_PAGO_TOTAL', 'ESTADO_PAGO', 'METODO_PAGO', 'ESTADO_RESERVA',
           'TIPO_DOCUMENTO', 'TIPO_TEMPORADA', 'TIPO_HABITACION',
           'TIPO_ALOJAMIENTO', 'CIUDAD', 'DEPARTAMENTO'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/


/* ---------------------------------------------------------------------
   1. UBICACIÓN
   --------------------------------------------------------------------- */

CREATE TABLE departamento (
  id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre  VARCHAR2(60)  NOT NULL,
  CONSTRAINT pk_departamento        PRIMARY KEY (id),
  CONSTRAINT uk_departamento_nombre UNIQUE (nombre)
);

COMMENT ON TABLE departamento IS 'Catálogo de departamentos. Agrupa las ciudades y permite filtrar los 12 municipios del Quindío.';

CREATE TABLE ciudad (
  id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre           VARCHAR2(60)  NOT NULL,
  id_departamento  NUMBER        NOT NULL,
  CONSTRAINT pk_ciudad              PRIMARY KEY (id),
  CONSTRAINT uk_ciudad_nombre_depto UNIQUE (nombre, id_departamento),
  CONSTRAINT fk_ciudad_departamento FOREIGN KEY (id_departamento) REFERENCES departamento (id)
);

COMMENT ON TABLE  ciudad                 IS 'Municipios del Quindío y ciudades de origen de los clientes. Cumple el papel de la entidad MUNICIPIO del modelo mínimo.';
COMMENT ON COLUMN ciudad.id_departamento IS 'Departamento al que pertenece la ciudad.';


/* ---------------------------------------------------------------------
   2. CATÁLOGOS
   --------------------------------------------------------------------- */

CREATE TABLE tipo_alojamiento (
  id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre  VARCHAR2(40)  NOT NULL,
  CONSTRAINT pk_tipo_alojamiento        PRIMARY KEY (id),
  CONSTRAINT uk_tipo_alojamiento_nombre UNIQUE (nombre)
);

COMMENT ON TABLE tipo_alojamiento IS 'Catálogo de tipos de alojamiento: finca cafetera, hotel, glamping, hostal, entre otros.';

CREATE TABLE tipo_habitacion (
  id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre  VARCHAR2(30)  NOT NULL,
  CONSTRAINT pk_tipo_habitacion        PRIMARY KEY (id),
  CONSTRAINT uk_tipo_habitacion_nombre UNIQUE (nombre)
);

COMMENT ON TABLE tipo_habitacion IS 'Catálogo de tipos de habitación: sencilla, doble, suite, cabaña.';

CREATE TABLE tipo_temporada (
  id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre  VARCHAR2(10)  NOT NULL,
  CONSTRAINT pk_tipo_temporada        PRIMARY KEY (id),
  CONSTRAINT uk_tipo_temporada_nombre UNIQUE (nombre)
);

COMMENT ON TABLE tipo_temporada IS 'Catálogo de tipos de temporada: alta, media y baja.';

CREATE TABLE tipo_documento (
  id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre  VARCHAR2(30)  NOT NULL,
  CONSTRAINT pk_tipo_documento        PRIMARY KEY (id),
  CONSTRAINT uk_tipo_documento_nombre UNIQUE (nombre)
);

COMMENT ON TABLE tipo_documento IS 'Catálogo de tipos de documento de identidad de los clientes.';

CREATE TABLE estado_reserva (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  descripcion  VARCHAR2(20)  NOT NULL,
  CONSTRAINT pk_estado_reserva             PRIMARY KEY (id),
  CONSTRAINT uk_estado_reserva_descripcion UNIQUE (descripcion)
);

COMMENT ON TABLE estado_reserva IS 'Catálogo de estados de reserva: pendiente, confirmada, cancelada, completada. Aplica a la reserva y a cada habitación reservada.';

CREATE TABLE metodo_pago (
  id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre  VARCHAR2(30)  NOT NULL,
  CONSTRAINT pk_metodo_pago        PRIMARY KEY (id),
  CONSTRAINT uk_metodo_pago_nombre UNIQUE (nombre)
);

COMMENT ON TABLE metodo_pago IS 'Catálogo de métodos de pago: tarjeta de crédito, tarjeta débito, PSE, transferencia, efectivo.';

CREATE TABLE estado_pago (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  descripcion  VARCHAR2(20)  NOT NULL,
  CONSTRAINT pk_estado_pago             PRIMARY KEY (id),
  CONSTRAINT uk_estado_pago_descripcion UNIQUE (descripcion)
);

COMMENT ON TABLE estado_pago IS 'Catálogo de estados de un pago individual: exitoso, fallido, pendiente, reembolsado.';

CREATE TABLE estado_pago_total (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  descripcion  VARCHAR2(20)  NOT NULL,
  CONSTRAINT pk_estado_pago_total             PRIMARY KEY (id),
  CONSTRAINT uk_estado_pago_total_descripcion UNIQUE (descripcion)
);

COMMENT ON TABLE estado_pago_total IS 'Catálogo de estados del cobro total de una reserva: pendiente, abonado, pagado, reembolsado, cancelado.';


/* ---------------------------------------------------------------------
   3. ALOJAMIENTO
   --------------------------------------------------------------------- */

CREATE TABLE alojamiento (
  id                         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre_comercial           VARCHAR2(100) NOT NULL,
  direccion                  VARCHAR2(150) NOT NULL,
  calificacion_autoasignada  NUMBER(1)     NOT NULL,
  id_ciudad                  NUMBER        NOT NULL,
  id_tipo_alojamiento        NUMBER        NOT NULL,
  CONSTRAINT pk_alojamiento                  PRIMARY KEY (id),
  CONSTRAINT ck_alojamiento_calificacion     CHECK (calificacion_autoasignada BETWEEN 1 AND 5),
  CONSTRAINT fk_alojamiento_ciudad           FOREIGN KEY (id_ciudad)           REFERENCES ciudad (id),
  CONSTRAINT fk_alojamiento_tipo_alojamiento FOREIGN KEY (id_tipo_alojamiento) REFERENCES tipo_alojamiento (id)
);

COMMENT ON TABLE  alojamiento                           IS 'Alojamientos de la plataforma (fincas, hoteles, glampings, hostales). Cada uno pertenece a un municipio y a un tipo.';
COMMENT ON COLUMN alojamiento.calificacion_autoasignada IS 'Estrellas de 1 a 5 que el alojamiento se asigna a sí mismo. No es el promedio de reseñas.';
COMMENT ON COLUMN alojamiento.id_ciudad                 IS 'Municipio del Quindío donde está el alojamiento.';

CREATE TABLE telefono_alojamiento (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  numero          VARCHAR2(20)  NOT NULL,
  id_alojamiento  NUMBER        NOT NULL,
  CONSTRAINT pk_telefono_alojamiento             PRIMARY KEY (id),
  CONSTRAINT fk_telefono_alojamiento_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id)
);

COMMENT ON TABLE telefono_alojamiento IS 'Teléfonos de contacto de cada alojamiento (uno o varios).';

CREATE TABLE correo_alojamiento (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  correo          VARCHAR2(100) NOT NULL,
  id_alojamiento  NUMBER        NOT NULL,
  CONSTRAINT pk_correo_alojamiento             PRIMARY KEY (id),
  CONSTRAINT fk_correo_alojamiento_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id)
);

COMMENT ON TABLE correo_alojamiento IS 'Correos electrónicos de contacto de cada alojamiento (cero o varios).';

CREATE TABLE habitacion (
  id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  numero              VARCHAR2(10)  NOT NULL,
  capacidad_maxima    NUMBER(2)     NOT NULL,
  descripcion         VARCHAR2(300),
  id_alojamiento      NUMBER        NOT NULL,
  id_tipo_habitacion  NUMBER        NOT NULL,
  CONSTRAINT pk_habitacion                 PRIMARY KEY (id),
  CONSTRAINT uk_habitacion_alojamiento_num UNIQUE (id_alojamiento, numero),
  CONSTRAINT ck_habitacion_capacidad       CHECK (capacidad_maxima > 0),
  CONSTRAINT fk_habitacion_alojamiento     FOREIGN KEY (id_alojamiento)     REFERENCES alojamiento (id),
  CONSTRAINT fk_habitacion_tipo_habitacion FOREIGN KEY (id_tipo_habitacion) REFERENCES tipo_habitacion (id)
);

COMMENT ON TABLE  habitacion                  IS 'Habitaciones de cada alojamiento. El número es único dentro del alojamiento.';
COMMENT ON COLUMN habitacion.capacidad_maxima IS 'Número máximo de huéspedes. Sp_crear_reserva lo valida (Entrega 2).';


/* ---------------------------------------------------------------------
   4. TEMPORADAS Y TARIFAS
   --------------------------------------------------------------------- */

CREATE TABLE temporada (
  id                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre             VARCHAR2(60)  NOT NULL,
  fecha_inicio       DATE          NOT NULL,
  fecha_fin          DATE          NOT NULL,
  id_tipo_temporada  NUMBER        NOT NULL,
  CONSTRAINT pk_temporada                PRIMARY KEY (id),
  CONSTRAINT ck_temporada_fechas         CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT fk_temporada_tipo_temporada FOREIGN KEY (id_tipo_temporada) REFERENCES tipo_temporada (id)
);

COMMENT ON TABLE temporada IS 'Temporadas definidas por el departamento para cada año, con su rango de fechas y su tipo (alta, media o baja).';

CREATE TABLE tarifa (
  id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  valor_noche    NUMBER(12,2)  NOT NULL,
  id_habitacion  NUMBER        NOT NULL,
  id_temporada   NUMBER        NOT NULL,
  CONSTRAINT pk_tarifa                PRIMARY KEY (id),
  CONSTRAINT uk_tarifa_hab_temporada  UNIQUE (id_habitacion, id_temporada),
  CONSTRAINT ck_tarifa_valor_noche    CHECK (valor_noche > 0),
  CONSTRAINT fk_tarifa_habitacion     FOREIGN KEY (id_habitacion) REFERENCES habitacion (id),
  CONSTRAINT fk_tarifa_temporada      FOREIGN KEY (id_temporada)  REFERENCES temporada (id)
);

COMMENT ON TABLE  tarifa             IS 'Valor por noche de una habitación en una temporada. Una fila por cada combinación habitación x temporada.';
COMMENT ON COLUMN tarifa.valor_noche IS 'Precio por noche fijado por el alojamiento. No es un porcentaje sobre un precio base.';


/* ---------------------------------------------------------------------
