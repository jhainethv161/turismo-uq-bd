COMMENT ON TABLE  cliente           IS 'Clientes registrados en la plataforma. Un cliente puede tener muchas reservas.';
COMMENT ON COLUMN cliente.id_ciudad IS 'Ciudad de origen del cliente (puede estar fuera del Quindío).';

CREATE TABLE telefono_cliente (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
