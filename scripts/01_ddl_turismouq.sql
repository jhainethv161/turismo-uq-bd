  id_cliente  NUMBER        NOT NULL,
  CONSTRAINT pk_telefono_cliente         PRIMARY KEY (id),
  CONSTRAINT fk_telefono_cliente_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id)
);

COMMENT ON TABLE telefono_cliente IS 'Teléfonos de contacto de cada cliente (uno o varios).';


/* ---------------------------------------------------------------------
   6. USUARIOS DEL SISTEMA
   --------------------------------------------------------------------- */

-- USUARIO_SISTEMA: usuarios internos de la plataforma. Un ADMINISTRADOR
-- gestiona toda la plataforma y no tiene alojamiento; un ENCARGADO
-- gestiona un alojamiento y siempre lo tiene asignado.
CREATE TABLE usuario_sistema (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  username        VARCHAR2(30)  NOT NULL,
  nombre          VARCHAR2(100) NOT NULL,
  correo          VARCHAR2(100) NOT NULL,
  activo          CHAR(1)       NOT NULL,
  rol             VARCHAR2(20)  NOT NULL,
  id_alojamiento  NUMBER,
  CONSTRAINT pk_usuario_sistema               PRIMARY KEY (id),
  CONSTRAINT uk_usuario_sistema_username      UNIQUE (username),
  CONSTRAINT uk_usuario_sistema_correo        UNIQUE (correo),
  CONSTRAINT ck_usuario_sistema_activo        CHECK (activo IN ('S', 'N')),
  CONSTRAINT ck_usuario_sistema_rol           CHECK (rol IN ('ADMINISTRADOR', 'ENCARGADO')),
  CONSTRAINT ck_usuario_sistema_rol_aloj      CHECK ((rol = 'ENCARGADO'     AND id_alojamiento IS NOT NULL)
                                                  OR (rol = 'ADMINISTRADOR' AND id_alojamiento IS NULL)),
  CONSTRAINT fk_usuario_sistema_alojamiento   FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id)
);

COMMENT ON TABLE  usuario_sistema                IS 'Usuarios internos de TurismoUQ: administradores de la plataforma y encargados de alojamiento.';
COMMENT ON COLUMN usuario_sistema.activo         IS 'S = usuario activo, N = usuario inactivo.';
COMMENT ON COLUMN usuario_sistema.rol            IS 'ADMINISTRADOR (toda la plataforma) o ENCARGADO (un alojamiento).';
COMMENT ON COLUMN usuario_sistema.id_alojamiento IS 'Alojamiento que gestiona el encargado. Obligatorio para ENCARGADO y NULL para ADMINISTRADOR.';


/* ---------------------------------------------------------------------
   7. SERVICIOS COMPLEMENTARIOS
   --------------------------------------------------------------------- */

CREATE TABLE servicio (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre          VARCHAR2(60)  NOT NULL,
  descripcion     VARCHAR2(300),
  precio          NUMBER(12,2)  NOT NULL,
  id_alojamiento  NUMBER        NOT NULL,
  CONSTRAINT pk_servicio                PRIMARY KEY (id),
  CONSTRAINT uk_servicio_aloj_nombre    UNIQUE (id_alojamiento, nombre),
  CONSTRAINT ck_servicio_precio         CHECK (precio >= 0),
  CONSTRAINT fk_servicio_alojamiento    FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id)
);

COMMENT ON TABLE servicio IS 'Servicios complementarios (desayuno, tour, transporte, spa...). Cada servicio pertenece a un alojamiento específico.';


/* ---------------------------------------------------------------------
   8. RESERVAS
   --------------------------------------------------------------------- */

CREATE TABLE reserva (
  id                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha_creacion     DATE          NOT NULL,
  fecha_check_in     DATE          NOT NULL,
  fecha_check_out    DATE          NOT NULL,
  fecha_cancelacion  DATE,
  id_cliente         NUMBER        NOT NULL,
  id_alojamiento     NUMBER        NOT NULL,
  id_estado_reserva  NUMBER        NOT NULL,
  CONSTRAINT pk_reserva                PRIMARY KEY (id),
  CONSTRAINT ck_reserva_fechas         CHECK (fecha_check_out > fecha_check_in),
  CONSTRAINT fk_reserva_cliente        FOREIGN KEY (id_cliente)        REFERENCES cliente (id),
  CONSTRAINT fk_reserva_alojamiento    FOREIGN KEY (id_alojamiento)    REFERENCES alojamiento (id),
  CONSTRAINT fk_reserva_estado_reserva FOREIGN KEY (id_estado_reserva) REFERENCES estado_reserva (id)
);

COMMENT ON TABLE  reserva                   IS 'Reserva de un cliente en un alojamiento. Puede incluir varias habitaciones (RESERVA_HABITACION).';
COMMENT ON COLUMN reserva.fecha_check_in    IS 'Inicio del rango general de la reserva.';
COMMENT ON COLUMN reserva.fecha_check_out   IS 'Fin del rango general de la reserva.';
COMMENT ON COLUMN reserva.fecha_cancelacion IS 'Fecha en que se canceló la reserva completa. NULL si no se ha cancelado. Con más de 5 días de anticipación al check-in aplica reembolso del 80 %.';
COMMENT ON COLUMN reserva.id_alojamiento    IS 'Alojamiento de la reserva. Todas sus habitaciones y servicios deben ser de este alojamiento (lo valida el procedimiento).';

CREATE TABLE reserva_habitacion (
  id                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha_check_in     DATE          NOT NULL,
  fecha_check_out    DATE          NOT NULL,
  numero_huespedes   NUMBER(2)     NOT NULL,
  valor_estadia      NUMBER(12,2)  NOT NULL,
  fecha_cancelacion  DATE,
  id_reserva         NUMBER        NOT NULL,
  id_habitacion      NUMBER        NOT NULL,
  id_estado_reserva  NUMBER        NOT NULL,
  CONSTRAINT pk_reserva_habitacion                PRIMARY KEY (id),
  CONSTRAINT uk_reserva_habitacion_res_hab        UNIQUE (id_reserva, id_habitacion),
  CONSTRAINT ck_reserva_habitacion_fechas         CHECK (fecha_check_out > fecha_check_in),
  CONSTRAINT ck_reserva_habitacion_huespedes      CHECK (numero_huespedes > 0),
  CONSTRAINT ck_reserva_habitacion_valor          CHECK (valor_estadia >= 0),
  CONSTRAINT fk_reserva_habitacion_reserva        FOREIGN KEY (id_reserva)        REFERENCES reserva (id),
  CONSTRAINT fk_reserva_habitacion_habitacion     FOREIGN KEY (id_habitacion)     REFERENCES habitacion (id),
  CONSTRAINT fk_reserva_habitacion_estado_reserva FOREIGN KEY (id_estado_reserva) REFERENCES estado_reserva (id)
);

COMMENT ON TABLE  reserva_habitacion                   IS 'Línea de reserva: una habitación dentro de una reserva, con sus propias fechas, huéspedes, valor y estado.';
COMMENT ON COLUMN reserva_habitacion.valor_estadia     IS 'Valor de la estadía calculado al reservar (fn_valor_estadia, Entrega 2). Debe ser igual a la suma de sus noches en RESERVA_NOCHE.';
COMMENT ON COLUMN reserva_habitacion.fecha_cancelacion IS 'Fecha de cancelación de esta habitación. NULL si no se ha cancelado. La regla del 80 % se calcula con esta fecha.';

CREATE TABLE reserva_noche (
  id                     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha                  DATE          NOT NULL,
  valor_noche            NUMBER(12,2)  NOT NULL,
  id_reserva_habitacion  NUMBER        NOT NULL,
  id_tarifa              NUMBER        NOT NULL,
  CONSTRAINT pk_reserva_noche                    PRIMARY KEY (id),
  CONSTRAINT uk_reserva_noche_linea_fecha        UNIQUE (id_reserva_habitacion, fecha),
  CONSTRAINT ck_reserva_noche_valor              CHECK (valor_noche > 0),
  CONSTRAINT fk_reserva_noche_reserva_habitacion FOREIGN KEY (id_reserva_habitacion) REFERENCES reserva_habitacion (id),
  CONSTRAINT fk_reserva_noche_tarifa             FOREIGN KEY (id_tarifa)             REFERENCES tarifa (id)
);

COMMENT ON TABLE  reserva_noche             IS 'Detalle noche por noche de cada habitación reservada, con la tarifa (y por tanto la temporada) aplicada a cada noche.';
COMMENT ON COLUMN reserva_noche.valor_noche IS 'Valor cobrado esa noche, copiado de TARIFA al reservar para conservar el precio histórico.';

CREATE TABLE reserva_servicio (
  id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  cantidad         NUMBER(3)     NOT NULL,
  precio_unitario  NUMBER(12,2)  NOT NULL,
  id_reserva       NUMBER        NOT NULL,
  id_servicio      NUMBER        NOT NULL,
  CONSTRAINT pk_reserva_servicio          PRIMARY KEY (id),
  CONSTRAINT uk_reserva_servicio_res_serv UNIQUE (id_reserva, id_servicio),
  CONSTRAINT ck_reserva_servicio_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_reserva_servicio_precio   CHECK (precio_unitario >= 0),
  CONSTRAINT fk_reserva_servicio_reserva  FOREIGN KEY (id_reserva)  REFERENCES reserva (id),
  CONSTRAINT fk_reserva_servicio_servicio FOREIGN KEY (id_servicio) REFERENCES servicio (id)
);

COMMENT ON TABLE  reserva_servicio                 IS 'Servicios complementarios incluidos en una reserva, con la cantidad pedida (por ejemplo, 2 tours guiados).';
COMMENT ON COLUMN reserva_servicio.precio_unitario IS 'Precio del servicio al momento de contratarlo, para conservar el precio histórico.';


/* ---------------------------------------------------------------------
   9. PAGOS
   --------------------------------------------------------------------- */

CREATE TABLE pago_total (
  id                    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  subtotal              NUMBER(12,2)  NOT NULL,
  total                 NUMBER(12,2),
  id_reserva            NUMBER        NOT NULL,
  id_estado_pago_total  NUMBER        NOT NULL,
  CONSTRAINT pk_pago_total             PRIMARY KEY (id),
  CONSTRAINT uk_pago_total_reserva     UNIQUE (id_reserva),
  CONSTRAINT ck_pago_total_subtotal    CHECK (subtotal >= 0),
  CONSTRAINT ck_pago_total_total       CHECK (total >= 0),
  CONSTRAINT fk_pago_total_reserva     FOREIGN KEY (id_reserva)           REFERENCES reserva (id),
  CONSTRAINT fk_pago_total_estado      FOREIGN KEY (id_estado_pago_total) REFERENCES estado_pago_total (id)
);

COMMENT ON TABLE  pago_total                      IS 'Consolidado de cobro de una reserva: valor de la estadía más los servicios. Una fila por reserva. Sin descuentos ni impuestos.';
COMMENT ON COLUMN pago_total.total                IS 'Total a pagar. Lo calcula el procedimiento de la Entrega 2, por eso admite NULL mientras no se calcule.';
COMMENT ON COLUMN pago_total.id_estado_pago_total IS 'Estado del cobro: pagado cuando la suma de los pagos exitosos cubre el total.';

CREATE TABLE pago (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha           DATE          NOT NULL,
  monto           NUMBER(12,2)  NOT NULL,
  id_pago_total   NUMBER        NOT NULL,
  id_metodo_pago  NUMBER        NOT NULL,
  id_estado_pago  NUMBER        NOT NULL,
  CONSTRAINT pk_pago             PRIMARY KEY (id),
  CONSTRAINT ck_pago_monto       CHECK (monto > 0),
  CONSTRAINT fk_pago_pago_total  FOREIGN KEY (id_pago_total)  REFERENCES pago_total (id),
  CONSTRAINT fk_pago_metodo_pago FOREIGN KEY (id_metodo_pago) REFERENCES metodo_pago (id),
  CONSTRAINT fk_pago_estado_pago FOREIGN KEY (id_estado_pago) REFERENCES estado_pago (id)
);

COMMENT ON TABLE  pago       IS 'Pagos de una reserva: puede pagarse de una vez o en varios abonos. Un reembolso es un pago nuevo con estado reembolsado.';
COMMENT ON COLUMN pago.monto IS 'Siempre positivo. El reembolso se distingue por su estado, no por el signo.';


/* ---------------------------------------------------------------------
   10. RESEÑAS
   --------------------------------------------------------------------- */

CREATE TABLE resena (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  calificacion  NUMBER(1)      NOT NULL,
  comentario    VARCHAR2(1000),
  fecha         DATE           NOT NULL,
  id_reserva    NUMBER         NOT NULL,
  CONSTRAINT pk_resena              PRIMARY KEY (id),
  CONSTRAINT uk_resena_reserva      UNIQUE (id_reserva),
  CONSTRAINT ck_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5),
