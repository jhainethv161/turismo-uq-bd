   EJECUTAR CONECTADO COMO EL DUEÑO DEL ESQUEMA (ej. TURISMOUQ).
   Requiere: scripts de la Entrega 1 y script 05.

   Crea tres tablas nuevas:
     AUDITORIA_TARIFA    -> la llena el disparador de auditoria de TARIFA
     LIQUIDACION_MENSUAL -> la llena el proceso masivo con cursor
     RESERVA_HISTORICO   -> vive en el tablespace TS_TURISMOUQ_HIST

   Las tres usan IDENTITY "BY DEFAULT ON NULL": si el INSERT no trae id
   (o lo trae en NULL) Oracle lo genera.
   ===================================================================== */

SET SERVEROUTPUT ON
SET SQLBLANKLINES ON

/* ---------------------------------------------------------------------
   0. Borrado previo para poder re-ejecutar el script en desarrollo.
      ORA-00942 = la tabla no existe (primera ejecucion): se ignora.
   --------------------------------------------------------------------- */
DECLARE
  PROCEDURE borrar(p_tabla VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE ' || p_tabla || ' CASCADE CONSTRAINTS PURGE';
    DBMS_OUTPUT.PUT_LINE('Tabla ' || p_tabla || ' eliminada.');
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE <> -942 THEN RAISE; END IF;
  END borrar;
BEGIN
  borrar('AUDITORIA_TARIFA');
  borrar('LIQUIDACION_MENSUAL');
  borrar('RESERVA_HISTORICO');
END;
/

/* ---------------------------------------------------------------------
   1. AUDITORIA_TARIFA
      Una fila por cada tarifa insertada, modificada o eliminada.
      Responde: QUIEN (usuario BD, usuario SO, equipo), CUANDO
      (fecha_cambio) y QUE (valor anterior y valor nuevo).
      No tiene FK a TARIFA a proposito: si una tarifa se elimina, su
      rastro de auditoria debe sobrevivir.
   --------------------------------------------------------------------- */
CREATE TABLE auditoria_tarifa (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_tarifa       NUMBER        NOT NULL,
  id_habitacion   NUMBER        NOT NULL,
  id_temporada    NUMBER        NOT NULL,
  operacion       VARCHAR2(6)   NOT NULL,
  valor_anterior  NUMBER(12,2),
  valor_nuevo     NUMBER(12,2),
  usuario_bd      VARCHAR2(128) NOT NULL,
  usuario_so      VARCHAR2(128),
  equipo          VARCHAR2(128),
  fecha_cambio    TIMESTAMP     NOT NULL,
  CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id),
  CONSTRAINT ck_aud_tarifa_operacion CHECK (operacion IN ('INSERT','UPDATE','DELETE')),
  -- coherencia: un INSERT no tiene valor anterior, un DELETE no tiene valor nuevo
  CONSTRAINT ck_aud_tarifa_valores CHECK (
       (operacion = 'INSERT' AND valor_anterior IS NULL     AND valor_nuevo IS NOT NULL)
    OR (operacion = 'UPDATE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NOT NULL)
    OR (operacion = 'DELETE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NULL) )
);

COMMENT ON TABLE  auditoria_tarifa IS 'Auditoria de cambios sobre TARIFA: quien, cuando, valor anterior y nuevo. La llena TRG_AUDITORIA_TARIFA.';
COMMENT ON COLUMN auditoria_tarifa.usuario_bd   IS 'Usuario de base de datos que ejecuto el cambio (SESSION_USER)';
COMMENT ON COLUMN auditoria_tarifa.usuario_so   IS 'Usuario del sistema operativo del cliente (OS_USER)';
COMMENT ON COLUMN auditoria_tarifa.equipo       IS 'Equipo desde el que se conecto (HOST)';
COMMENT ON COLUMN auditoria_tarifa.fecha_cambio IS 'Momento exacto del cambio';

/* ---------------------------------------------------------------------
   2. LIQUIDACION_MENSUAL
      Resultado del proceso masivo PKG_TURISMO.SP_LIQUIDACION_MENSUAL:
      una fila por alojamiento y mes (aunque no haya tenido ventas).
      UNIQUE (anio, mes, id_alojamiento): si el proceso se corre de
      nuevo para el mismo mes, reemplaza la liquidacion anterior.
   --------------------------------------------------------------------- */
CREATE TABLE liquidacion_mensual (
  id                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  anio               NUMBER(4)     NOT NULL,
  mes                NUMBER(2)     NOT NULL,
  id_alojamiento     NUMBER        NOT NULL,
  noches_ocupadas    NUMBER(8)     DEFAULT 0 NOT NULL,
  num_reservas       NUMBER(8)     DEFAULT 0 NOT NULL,
  ingreso_estadia    NUMBER(14,2)  DEFAULT 0 NOT NULL,
  ingreso_servicios  NUMBER(14,2)  DEFAULT 0 NOT NULL,
  ingreso_total      NUMBER(14,2)  DEFAULT 0 NOT NULL,
  fecha_generacion   DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_liquidacion_mensual PRIMARY KEY (id),
  CONSTRAINT uk_liquidacion_periodo UNIQUE (anio, mes, id_alojamiento),
  CONSTRAINT fk_liquidacion_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id),
  CONSTRAINT ck_liquidacion_mes CHECK (mes BETWEEN 1 AND 12),
  CONSTRAINT ck_liquidacion_positivos CHECK (noches_ocupadas >= 0 AND num_reservas >= 0
                                             AND ingreso_estadia >= 0 AND ingreso_servicios >= 0),
  CONSTRAINT ck_liquidacion_total CHECK (ingreso_total = ingreso_estadia + ingreso_servicios)
);

COMMENT ON TABLE  liquidacion_mensual IS 'Liquidacion mensual por alojamiento generada con un cursor explicito parametrizado (PKG_TURISMO.SP_LIQUIDACION_MENSUAL).';
COMMENT ON COLUMN liquidacion_mensual.noches_ocupadas   IS 'Noches vendidas en el mes (RESERVA_NOCHE con cabecera confirmada/completada y linea no cancelada)';
COMMENT ON COLUMN liquidacion_mensual.num_reservas      IS 'Reservas distintas con al menos una noche en el mes';
COMMENT ON COLUMN liquidacion_mensual.ingreso_estadia   IS 'Suma del valor_noche congelado de esas noches';
COMMENT ON COLUMN liquidacion_mensual.ingreso_servicios IS 'Servicios de las reservas cuyo check-in cae en el mes';
COMMENT ON COLUMN liquidacion_mensual.ingreso_total     IS 'ingreso_estadia + ingreso_servicios';

/* ---------------------------------------------------------------------
   3. RESERVA_HISTORICO  (en el tablespace TS_TURISMOUQ_HIST)
      Foto desnormalizada de cada linea de reserva ya cerrada
      (COMPLETADA o CANCELADA) de un periodo anterior a una fecha de
      corte. Se guarda desnormalizada (nombre del cliente, municipio,
      tipo...) para que el historico se pueda consultar solo, sin
      depender de que los catalogos no cambien.
      Tanto la tabla como el indice de su PK van al tablespace propio.
   --------------------------------------------------------------------- */
CREATE TABLE reserva_historico (
  id_reserva_habitacion NUMBER        NOT NULL,
  id_reserva            NUMBER        NOT NULL,
  fecha_creacion        DATE          NOT NULL,
  id_cliente            NUMBER        NOT NULL,
  numero_documento      VARCHAR2(20)  NOT NULL,
  nombre_cliente        VARCHAR2(121) NOT NULL,
  id_alojamiento        NUMBER        NOT NULL,
  nombre_alojamiento    VARCHAR2(100) NOT NULL,
  municipio             VARCHAR2(60)  NOT NULL,
  tipo_alojamiento      VARCHAR2(40)  NOT NULL,
  id_habitacion         NUMBER        NOT NULL,
  numero_habitacion     VARCHAR2(10)  NOT NULL,
  fecha_check_in        DATE          NOT NULL,
  fecha_check_out       DATE          NOT NULL,
  noches                NUMBER(4)     NOT NULL,
  numero_huespedes      NUMBER(2)     NOT NULL,
  valor_estadia         NUMBER(12,2)  NOT NULL,
  estado                VARCHAR2(20)  NOT NULL,
  fecha_cancelacion     DATE,
  fecha_archivo         DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_reserva_historico PRIMARY KEY (id_reserva_habitacion)
    USING INDEX TABLESPACE ts_turismouq_hist,
  CONSTRAINT ck_hist_fechas CHECK (fecha_check_out > fecha_check_in)
)
TABLESPACE ts_turismouq_hist;

COMMENT ON TABLE  reserva_historico IS 'Historico de lineas de reserva cerradas (cabecera y linea completadas o canceladas). Vive en TS_TURISMOUQ_HIST. Lo llena PKG_TURISMO.SP_ARCHIVAR_HISTORICO.';
COMMENT ON COLUMN reserva_historico.fecha_archivo IS 'Fecha en que la linea se copio al historico';

-- Verificacion: RESERVA_HISTORICO debe aparecer en TS_TURISMOUQ_HIST
SELECT table_name, tablespace_name
FROM   user_tables
WHERE  table_name IN ('AUDITORIA_TARIFA','LIQUIDACION_MENSUAL','RESERVA_HISTORICO')
ORDER  BY table_name;
